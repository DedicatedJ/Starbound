#!/usr/bin/env python3
"""Generate the game's data files (src/data/*.lua) from the lore vault (lore/).

The vault is the source of truth for every tunable number. Each note whose
properties include `game_kind` becomes game data:

    weapon, enemy, pickup, upgrade, location, balance

Usage:
    python tools/gen_data.py          write src/data/*.lua
    python tools/gen_data.py --check  exit 1 if any generated file is out of date

Requires PyYAML (pip install pyyaml). Only this tool and CI use it; the game
itself never reads the vault.
"""
import math
import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
LORE = ROOT / "lore"
DATA = ROOT / "src" / "data"
FRONTMATTER = re.compile(r"\A---\r?\n(.*?)\r?\n---\r?\n", re.S)
LINK = re.compile(r"^\[\[([^\]|#]+)(?:[|#][^\]]*)?\]\]$")

HEADER = (
    "-- GENERATED by tools/gen_data.py from the lore vault ({source}).\n"
    "-- Do not edit this file: change the note properties in lore/ and run\n"
    "--     python tools/gen_data.py\n"
)

# Property schemas: name -> (type, required). Types: num, int, str, bool, list, link
NUM, INT, STR, BOOL, LIST, LINK_T = "num", "int", "str", "bool", "list", "link"
SCHEMAS = {
    "weapon": {
        "game_id": (STR, True), "order": (INT, True),
        "damage": (NUM, True), "fire_cooldown": (NUM, True), "energy_cost": (NUM, True),
        "range": (NUM, True), "projectile_speed": (NUM, True), "projectile_size": (NUM, True),
        "projectile_count": (INT, True), "spread_degrees": (NUM, True),
        "charge_time": (NUM, True), "pierce_count": (INT, True),
    },
    "enemy": {
        "game_id": (STR, True), "game_name": (STR, False),
        "health": (NUM, True), "damage": (NUM, True), "move_speed": (NUM, True),
        "attack_range": (NUM, True), "attack_cooldown": (NUM, True),
        "patrol_radius": (NUM, True), "chase_range": (NUM, True), "retreat_health": (NUM, True),
        "strafe_speed": (NUM, False), "strafe_range": (NUM, False), "formation_spacing": (NUM, False),
    },
    "pickup": {
        "game_id": (STR, True), "game_name": (STR, False),
        "value": (NUM, True), "lifetime": (NUM, True),
    },
    "upgrade": {
        "game_id": (STR, True), "game_name": (STR, False), "order": (INT, True),
        "upgrade_kind": (STR, True), "shop_text": (STR, True),
        "cost_salvage": (INT, False), "cost_alien_essence": (INT, False),
        "bonus_max_health": (NUM, False), "bonus_max_shield": (NUM, False),
        "bonus_max_energy": (NUM, False), "bonus_energy_recharge": (NUM, False),
        "jump_range_bonus": (NUM, False), "max_fuel_bonus": (INT, False),
    },
    "location": {
        "game_id": (STR, True), "game_name": (STR, False), "order": (INT, True),
        "location_kind": (STR, True), "map_x": (NUM, True), "map_y": (NUM, True),
        "biomes": (LIST, True), "level_bonus": (INT, True), "map_text": (STR, True),
        "safe": (BOOL, False), "has_fragment": (BOOL, False), "puzzle": (STR, False),
        "requires_fragments": (INT, False), "requires_upgrade": (LINK_T, False),
    },
    "balance": {
        "game_id": (STR, True),
        "player_max_health": (NUM, True), "player_max_shield": (NUM, True),
        "player_max_energy": (NUM, True), "player_energy_recharge": (NUM, True),
        "player_shield_recharge_rate": (NUM, True), "player_shield_recharge_delay": (NUM, True),
        "player_move_speed": (NUM, True), "player_inventory_size": (INT, True),
        "max_weapon_level": (INT, True), "enemy_level_scaling": (NUM, True),
        "chunks_per_level": (NUM, True), "enemy_spawn_chance": (NUM, True),
        "max_enemies_per_chunk": (INT, True), "base_jump_range": (NUM, True),
        "base_max_fuel": (INT, True), "fuel_per_jump": (INT, True),
        "start_location": (LINK_T, True), "home_location": (LINK_T, True),
    },
}
# Enemy drop chances are properties named drop_<pickup id>. Drops are rolled in this
# order (it matters for reproducible runs); pickups not listed here roll last, by id.
DROP_ORDER = ["health_crystal", "energy_crystal", "weapon_upgrade", "shield_crystal",
              "repair_kit", "salvage", "alien_essence"]
MATERIALS = ["salvage", "alien_essence"]
UPGRADE_KINDS = {"ship", "gear"}
VAULT_PUZZLES = {"sequence", "resonance", "plates"}
BIOMES = {"jungle", "desert", "ice", "space_station"}


class VaultError(Exception):
    pass


def load_notes():
    notes = []
    for path in sorted(LORE.rglob("*.md")):
        rel = path.relative_to(LORE)
        if rel.parts[0].startswith(("_", ".")):
            continue
        text = path.read_text(encoding="utf-8")
        m = FRONTMATTER.match(text)
        if not m:
            continue
        try:
            props = yaml.safe_load(m.group(1)) or {}
        except yaml.YAMLError as e:
            raise VaultError(f"{rel}: properties are not valid YAML: {e}")
        notes.append((rel, path.stem, props))
    return notes


def check_type(rel, key, value, kind):
    ok = {
        NUM: isinstance(value, (int, float)) and not isinstance(value, bool),
        INT: isinstance(value, int) and not isinstance(value, bool),
        STR: isinstance(value, str) and value != "",
        BOOL: isinstance(value, bool),
        LIST: isinstance(value, list) and all(isinstance(x, str) for x in value) and value,
        LINK_T: isinstance(value, str) and bool(LINK.match(value)),
    }[kind]
    if not ok:
        want = {NUM: "a number", INT: "a whole number", STR: "text", BOOL: "true or false",
                LIST: "a list of text", LINK_T: "a link like [[Note]]"}[kind]
        raise VaultError(f"{rel}: property '{key}' must be {want}, got {value!r}")


def collect(notes):
    errors = []
    by_kind = {k: [] for k in SCHEMAS}
    titles = {}
    for rel, title, props in notes:
        titles[title.lower()] = props
        for alias in props.get("aliases") or []:
            titles.setdefault(str(alias).lower(), props)
        kind = props.get("game_kind")
        if kind is None:
            continue
        if kind not in SCHEMAS:
            errors.append(f"{rel}: unknown game_kind '{kind}' (expected one of {', '.join(SCHEMAS)})")
            continue
        schema = SCHEMAS[kind]
        entry = {"_rel": rel, "_title": title}
        for key, (ptype, required) in schema.items():
            if key not in props or props[key] is None:
                if required:
                    errors.append(f"{rel}: missing required property '{key}' for a {kind}")
                continue
            try:
                check_type(rel, key, props[key], ptype)
            except VaultError as e:
                errors.append(str(e))
                continue
            entry[key] = props[key]
        if kind == "enemy":
            for key, value in props.items():
                if key.startswith("drop_"):
                    try:
                        check_type(rel, key, value, NUM)
                        if not 0 <= value <= 1:
                            raise VaultError(f"{rel}: drop chance '{key}' must be between 0 and 1, got {value}")
                    except VaultError as e:
                        errors.append(str(e))
                        continue
                    entry[key] = value
        by_kind[kind].append(entry)
    if errors:
        raise VaultError("\n".join(errors))
    return by_kind, titles


def resolve(link, titles, rel, key, kind=None):
    target = LINK.match(link).group(1).strip()
    props = titles.get(target.lower())
    if props is None:
        raise VaultError(f"{rel}: '{key}' links to [[{target}]], which is not a note")
    if kind and props.get("game_kind") != kind:
        raise VaultError(f"{rel}: '{key}' links to [[{target}]], which is not a {kind} (game_kind: {kind})")
    return props["game_id"]


def validate(by_kind, titles):
    errors = []
    for kind, entries in by_kind.items():
        seen = {}
        orders = {}
        for e in entries:
            gid = e.get("game_id")
            if gid in seen:
                errors.append(f"{e['_rel']}: game_id '{gid}' is also used by {seen[gid]}")
            seen[gid] = e["_rel"]
            if "order" in e:
                if e["order"] in orders:
                    errors.append(f"{e['_rel']}: order {e['order']} is also used by {orders[e['order']]}")
                orders[e["order"]] = e["_rel"]
    if len(by_kind["balance"]) != 1:
        errors.append(f"expected exactly one note with game_kind: balance, found {len(by_kind['balance'])}")
    pickups = {e["game_id"] for e in by_kind["pickup"]}
    for e in by_kind["enemy"]:
        for key in e:
            if key.startswith("drop_") and key[5:] not in pickups:
                errors.append(f"{e['_rel']}: '{key}' names no pickup (pickup ids: {', '.join(sorted(pickups))})")
    for e in by_kind["upgrade"]:
        if e["upgrade_kind"] not in UPGRADE_KINDS:
            errors.append(f"{e['_rel']}: upgrade_kind must be ship or gear, got '{e['upgrade_kind']}'")
        if not any(e.get(f"cost_{m}") for m in MATERIALS):
            errors.append(f"{e['_rel']}: an upgrade needs a cost (cost_salvage and/or cost_alien_essence)")
    for e in by_kind["weapon"]:
        if e["fire_cooldown"] <= 0:
            errors.append(f"{e['_rel']}: fire_cooldown must be above 0")
        if e["projectile_count"] < 1:
            errors.append(f"{e['_rel']}: projectile_count must be at least 1")
    for e in by_kind["location"]:
        bad = [b for b in e["biomes"] if b not in BIOMES]
        if bad:
            errors.append(f"{e['_rel']}: unknown biome(s) {bad} (known: {', '.join(sorted(BIOMES))})")
        if e.get("has_fragment") and e.get("puzzle") not in VAULT_PUZZLES:
            errors.append(f"{e['_rel']}: a location with has_fragment needs puzzle: sequence, resonance or plates")
    if errors:
        raise VaultError("\n".join(errors))


# ---------------------------------------------------------------- Lua output
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def lua(value, indent=""):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return repr(value) if value != int(value) else f"{int(value)}"
    if isinstance(value, str):
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'
    inner = indent + "    "
    if isinstance(value, list):
        if all(not isinstance(x, (list, dict)) for x in value):
            return "{" + ", ".join(lua(x) for x in value) + "}"
        return "{\n" + "".join(f"{inner}{lua(x, inner)},\n" for x in value) + indent + "}"
    if isinstance(value, dict):
        if not value:
            return "{}"
        parts = []
        for k, v in value.items():
            key = k if IDENT.match(k) else f'["{k}"]'
            parts.append(f"{inner}{key} = {lua(v, inner)},\n")
        return "{\n" + "".join(parts) + indent + "}"
    raise TypeError(value)


def name_of(e):
    return e.get("game_name") or e["_title"]


def source_list(entries):
    return ", ".join(str(e["_rel"]).replace("\\", "/") for e in entries)


def build(by_kind, titles):
    files = {}
    ordered = lambda k: sorted(by_kind[k], key=lambda e: e.get("order", 0) or e["game_id"])

    weapons = []
    for e in ordered("weapon"):
        w = {"id": e["game_id"], "name": name_of(e), "damage": e["damage"], "fireRate": e["fire_cooldown"],
             "energyCost": e["energy_cost"], "range": e["range"], "projectileSpeed": e["projectile_speed"],
             "projectileSize": e["projectile_size"]}
        if e["projectile_count"] > 1:
            w["projectileCount"] = e["projectile_count"]
            w["spreadAngle"] = math.radians(e["spread_degrees"])
        if e["charge_time"] > 0:
            w["chargeTime"] = e["charge_time"]
        if e["pierce_count"] > 0:
            w["pierceCount"] = e["pierce_count"]
        weapons.append(w)
    files["weapons.lua"] = ("lore notes with game_kind: weapon", "Weapon stats, in switch order (keys 1 to 5)", weapons)

    rank = {pid: i for i, pid in enumerate(DROP_ORDER)}
    enemies = {}
    for e in sorted(by_kind["enemy"], key=lambda e: e["game_id"]):
        behavior = {k2: e[k1] for k1, k2 in [("patrol_radius", "patrolRadius"), ("chase_range", "chaseRange"),
                    ("retreat_health", "retreatHealth"), ("strafe_speed", "strafeSpeed"),
                    ("strafe_range", "strafeRange"), ("formation_spacing", "formationSpacing")] if k1 in e}
        drop_ids = sorted((k[5:] for k in e if k.startswith("drop_")), key=lambda p: (rank.get(p, len(rank)), p))
        enemies[e["game_id"]] = {
            "name": name_of(e), "health": e["health"], "damage": e["damage"], "moveSpeed": e["move_speed"],
            "attackRange": e["attack_range"], "attackCooldown": e["attack_cooldown"], "behavior": behavior,
            "drops": [{"item": p, "chance": e["drop_" + p]} for p in drop_ids if e["drop_" + p] > 0],
        }
    files["enemies.lua"] = ("lore notes with game_kind: enemy", "Enemy stats and drop chances, by enemy type", enemies)

    pickups = {e["game_id"]: {"name": name_of(e), "value": e["value"], "lifetime": e["lifetime"]}
               for e in sorted(by_kind["pickup"], key=lambda e: e["game_id"])}
    files["pickups.lua"] = ("lore notes with game_kind: pickup", "Pickup values and how long they stay on the ground", pickups)

    upgrades = []
    for e in ordered("upgrade"):
        u = {"id": e["game_id"], "name": name_of(e), "kind": e["upgrade_kind"],
             "cost": {m: e[f"cost_{m}"] for m in MATERIALS if e.get(f"cost_{m}")}}
        bonus = {k2: e[k1] for k1, k2 in [("bonus_max_health", "maxHealth"), ("bonus_max_shield", "maxShield"),
                 ("bonus_max_energy", "maxEnergy"), ("bonus_energy_recharge", "energyRechargeRate")] if e.get(k1)}
        if bonus:
            u["bonus"] = bonus
        if e.get("jump_range_bonus"):
            u["jumpRangeBonus"] = e["jump_range_bonus"]
        if e.get("max_fuel_bonus"):
            u["maxFuelBonus"] = e["max_fuel_bonus"]
        u["description"] = e["shop_text"]
        upgrades.append(u)
    files["upgrades.lua"] = ("lore notes with game_kind: upgrade", "Upgrades sold at the Drift Station terminal, in shop order", upgrades)

    bal = by_kind["balance"][0]
    locations = []
    for e in ordered("location"):
        loc = {"id": e["game_id"], "name": name_of(e), "kind": e["location_kind"], "x": e["map_x"], "y": e["map_y"],
               "biomes": e["biomes"], "levelBonus": e["level_bonus"]}
        if e.get("safe"):
            loc["safe"] = True
        if e.get("has_fragment"):
            loc["fragment"] = True
            loc["puzzle"] = e["puzzle"]
        req = {}
        if e.get("requires_fragments"):
            req["fragments"] = e["requires_fragments"]
        if e.get("requires_upgrade"):
            req["upgrade"] = resolve(e["requires_upgrade"], titles, e["_rel"], "requires_upgrade", "upgrade")
        if req:
            loc["requires"] = req
        loc["description"] = e["map_text"]
        locations.append(loc)
    galaxy = {
        "start": resolve(bal["start_location"], titles, bal["_rel"], "start_location", "location"),
        "home": resolve(bal["home_location"], titles, bal["_rel"], "home_location", "location"),
        "locations": locations,
    }
    files["galaxy.lua"] = ("lore notes with game_kind: location", "The locations on Mara Solis's star map (positions in map units, 0 to 1)", galaxy)

    balance = {
        "player": {"maxHealth": bal["player_max_health"], "maxShield": bal["player_max_shield"],
                   "maxEnergy": bal["player_max_energy"], "energyRechargeRate": bal["player_energy_recharge"],
                   "shieldRechargeRate": bal["player_shield_recharge_rate"],
                   "shieldRechargeDelay": bal["player_shield_recharge_delay"],
                   "moveSpeed": bal["player_move_speed"], "inventorySize": bal["player_inventory_size"],
                   "maxWeaponLevel": bal["max_weapon_level"]},
        "enemies": {"levelScaling": bal["enemy_level_scaling"]},
        "world": {"chunksPerLevel": bal["chunks_per_level"], "enemySpawnChance": bal["enemy_spawn_chance"],
                  "maxEnemiesPerChunk": bal["max_enemies_per_chunk"]},
        "travel": {"baseJumpRange": bal["base_jump_range"], "baseMaxFuel": bal["base_max_fuel"],
                   "fuelPerJump": bal["fuel_per_jump"]},
    }
    files["balance.lua"] = (str(bal["_rel"]).replace("\\", "/"), "Game-wide balance numbers", balance)

    out = {}
    for name, (source, comment, data) in files.items():
        out[name] = HEADER.format(source=source) + f"-- {comment}\nreturn {lua(data)}\n"
    return out


def main():
    check = "--check" in sys.argv[1:]
    try:
        by_kind, titles = collect(load_notes())
        validate(by_kind, titles)
        files = build(by_kind, titles)
    except VaultError as e:
        print("Vault data error:\n" + str(e), file=sys.stderr)
        return 2
    stale = []
    for name, text in files.items():
        path = DATA / name
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current is not None:
            current = current.replace("\r\n", "\n")
        if current != text:
            stale.append(name)
            if not check:
                path.write_text(text, encoding="utf-8", newline="\n")
    if check:
        if stale:
            print("Out of date with the lore vault: " + ", ".join(f"src/data/{n}" for n in stale), file=sys.stderr)
            print("Run: python tools/gen_data.py", file=sys.stderr)
            return 1
        print("src/data is up to date with the lore vault")
        return 0
    print("Wrote " + ", ".join(f"src/data/{n}" for n in stale) if stale else "src/data already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
